import type { Cause, Interest, Skill } from "./types";
import type { PathfindIdea } from "./pathfindIdeas";

/**
 * The structured PATHFIND IDEA library. Every entry is an original project concept, never a
 * program or affiliation. Data sources named here are real public datasets or tools; the idea
 * itself is Pathfind's suggestion. Specs are kept terse and expanded into the full
 * `PathfindIdea` shape by `idea()` so the library stays reviewable.
 */
interface IdeaSpec {
  id: string;
  title: string;
  /** One-sentence hook: what the student makes. */
  summary: string;
  /** The concrete problem, in one or two sentences. */
  problem: string;
  /** Who uses or benefits from the finished project. */
  whoItHelps: string;
  /** What the finished project shows a mentor, program, or college. */
  portfolioValue: string;
  category: PathfindIdea["category"];
  interests: Interest[];
  causes: Cause[];
  skills?: Skill[];
  /** Words a student might type ("volleyball", "quant") that this idea genuinely covers. */
  topics?: string[];
  difficulty: PathfindIdea["difficulty"];
  hours: [number, number];
  weeks: [number, number];
  cost?: string;
  team: NonNullable<PathfindIdea["teamSize"]>;
  setting: NonNullable<PathfindIdea["setting"]>;
  needs: string[];
  learn: string[];
  tools: string[];
  data?: string;
  /** The first milestone — small enough to finish in the first week. */
  milestone: string;
  steps: string[];
  stretch: string;
  outputs: string[];
  related?: string[];
}

function idea(s: IdeaSpec): PathfindIdea {
  return {
    id: s.id,
    title: s.title,
    summary: s.summary,
    description: `${s.problem} ${s.portfolioValue}`,
    category: s.category,
    matchesInterests: s.interests,
    matchesCauses: s.causes,
    matchesSkills: s.skills,
    difficulty: s.difficulty,
    weeklyHours: `${s.hours[0]}-${s.hours[1]} hours`,
    minWeeklyHours: s.hours[0],
    duration: `${s.weeks[0]}-${s.weeks[1]} weeks`,
    cost: s.cost ?? "Free",
    skillsRequired: s.needs,
    skillsYouWillLearn: s.learn,
    firstStep: s.milestone,
    roadmap: [s.milestone, ...s.steps],
    deliverables: s.outputs,
    potentialImpact: s.whoItHelps,
    relatedOpportunityIds: s.related ?? [],
    problem: s.problem,
    whoItHelps: s.whoItHelps,
    tools: s.tools,
    dataSource: s.data,
    teamSize: s.team,
    setting: s.setting,
    stretchGoal: s.stretch,
    portfolioValue: s.portfolioValue,
    topics: s.topics,
  };
}

